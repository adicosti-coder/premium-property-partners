// Helpers for blog location archive pages (/blog/locatie/:location).
// Slugifies geo_location values consistently in app + sitemap.

export function slugifyLocation(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// Pretty label from a slug (fallback if no matching DB row exists)
export function prettifyLocationSlug(slug: string): string {
  return slug
    .split("-")
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}
