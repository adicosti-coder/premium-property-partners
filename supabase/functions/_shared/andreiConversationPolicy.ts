const _n = (t: string) => t.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
export const DEFENSIVE_COMMISSION_RE = /nu (oferim|facem|lucram|prestam)[^.?!]*(fara comision|gratis|gratuit)|nu lucram gratis/;

/** Verifică replica la comision: mod de lucru/procent + analiză gratuită + propunere WhatsApp, fără formulări defensive. */
export function validateCommissionReply(reply: string): { ok: boolean; missing: string[] } {
  const t = _n(reply);
  const missing: string[] = [];
  if (!/(la rezultat|comision|\d+\s*-\s*\d+\s*%|\d+\s*%)/.test(t)) missing.push("mod_lucru");
  if (!/(analiz\w*|raport\w*|evaluar\w*)[^.?!]*gratu|gratu\w*[^.?!]*(analiz|raport|evaluar)/.test(t)) missing.push("analiza_gratuita");
  if (!/whatsapp/.test(t)) missing.push("propunere_whatsapp");
  if (DEFENSIVE_COMMISSION_RE.test(t)) missing.push("formulare_defensiva");
  return { ok: missing.length === 0, missing };
}

export const SOFT_REFUSAL_RE = /(gasesc singur|caut singur|vand singur|inchiriez singur|ma descurc singur|nu platesc comision|nu dau comision|nu vreau comision|nu am nevoie de agenti|fara agentie)/;
export const HARD_STOP_RE = /(\bstop\b|nu ma mai (sunati|contactati)|stergeti|nu ma intereseaza.*inchid|inchid)/;
const QUALIFY_RE = /\?.*$|(eliberat|liber|disponibil|termen|cand|de cand|ce perioada)/;

/** True dacă Andrei a închis apelul după un refuz moale fără nicio încercare de calificare. */
export function isPrematureClose(ownerText: string, reply: string): boolean {
  const o = _n(ownerText), r = _n(reply);
  if (HARD_STOP_RE.test(o) || !SOFT_REFUSAL_RE.test(o)) return false;
  const closes = /o zi buna|nu va mai retin|la revedere/.test(r);
  const qualifies = r.includes("?") && QUALIFY_RE.test(r);
  return closes || !qualifies;
}
