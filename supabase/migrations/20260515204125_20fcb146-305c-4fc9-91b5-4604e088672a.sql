Conform **Legii 227/2015 (Codul Fiscal)**, art. 484-487, autoritățile locale pot institui o **taxă pentru șederea într-o unitate de cazare** (popular: „taxa hotelieră"). Consiliul Local Timișoara a stabilit prin **HCL 533/2024** și menținut pentru 2026 această taxă la **1% din valoarea totală a serviciului de cazare**, fără TVA.

## Cine colectează și cine plătește

- **Plătitor**: **oaspetele** (turistul) — taxa se evidențiază separat pe factură/bon
- **Colector**: **operatorul** unității de cazare (proprietar / firmă administrare)
- **Beneficiar**: **bugetul local Timișoara**

## Bază de calcul — ce intră și ce nu

**Intră** în baza de calcul:
- Cazarea în sine
- Mic dejun **inclus** în pachet
- Curățenie inclusă

**NU intră**:
- TVA
- Taxe de turism la nivel UE (dacă apar în viitor)
- Servicii suplimentare facturate separat (transport, tururi, parcare)
- Penalitățile pentru anulare

## Excepții (NU se aplică taxa)

- Persoane cu handicap grav/accentuat
- Pensionari (peste 65 ani la 1 ianuarie an fiscal)
- Elevi/studenți pe perioada școlarizării
- Sejururi sub **24 ore** (între ora 14:00 → 12:00 ziua următoare)
- Persoane cazate gratuit (familie host)

## Termenul de virament la Primăria Timișoara

- **Lunar**, până în **data de 25** a lunii următoare
- Cont special: TREZORERIE Timișoara, IBAN dedicat
- Se depune **Declarația D-100 locală** (formular tipizat PMT)

## Sancțiuni

- Necolectare: **500-2.500 lei**/incident
- Nevărsare în termen: dobânzi 0,01%/zi + penalitate 0,02%/zi
- Lipsă declarație lunară: **1.000-5.000 lei**

